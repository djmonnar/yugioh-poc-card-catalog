// Card catalog conveniences: page jumps, URL state, list conditions, thumbnails
// and bulk changes. Everything here is read-only presentation logic; edits still
// go through the panel's per-card patch path and the existing draft/store queue.
import {canonicalPositionCategories212} from './authoring131-category-aliases.js?v=20261126-position-taxonomy212';

export const CATALOG_FLAGS170=Object.freeze([
  ['uncategorized','분류 없음','카테고리가 하나도 없는 카드'],
  ['noImage','그림 없음','이미지 경로가 없거나 이 화면에서 그림을 불러오지 못한 카드'],
  ['problem','문제 있음','DB 확인 필요 표시, 거절된 저장, 사라진 관련 카드 연결이 있는 카드'],
  ['recent','최근 변경','웹 DB 공개 변경 기록에서 최근에 바뀐 카드']
]);
const FLAG_KEYS170=new Set(CATALOG_FLAGS170.map(([key])=>key));
const MULTI170=Object.freeze({type:'type',tier:'tier',race:'race',attribute:'attr',subtype:'sub',limit:'lim',speedLimit:'spd',status:'st',tags:'cat',flags170:'only'});
const SINGLE170=Object.freeze({query:'q',categoryMatch:'match',browse:'view',addition:'add',additionTheme:'theme',sort:'sort',recent170:'rc'});
export const CATALOG_PARAMS170=Object.freeze([...Object.values(MULTI170),...Object.values(SINGLE170),'page']);
const DEFAULTS170=Object.freeze({query:'',categoryMatch:'all',browse:'all',addition:'latest',additionTheme:'all',sort:null,recent170:null,page:1});
const cleanText=(value,max)=>{const text=String(value??'');return text.length<=max&&!/[\u0000-\u001f\u007f]/.test(text)?text:null;};
const list=value=>[...new Set((Array.isArray(value)?value:value==null||value===''?[]:[value]).map(String).filter(Boolean))];

export function pageNumber170(value,pages){
  const text=String(value??'').trim();if(!/^\d{1,7}$/.test(text))return null;
  return Math.min(Math.max(1,Number(text)),Math.max(1,Number.isSafeInteger(pages)?pages:1));
}

// Writes only non-default values, so a plain catalog keeps a short URL.
export function writeCatalogParams170(url,state={}){
  const params=url.searchParams;for(const key of CATALOG_PARAMS170)params.delete(key);
  for(const [field,key] of Object.entries(MULTI170)){
    const values=list(state[field]);
    for(const value of (field==='tags'?canonicalPositionCategories212(values):values).slice(0,64))params.append(key,value);
  }
  for(const [field,key] of Object.entries(SINGLE170)){
    // Addition group and theme only matter in the 최근 추가 view.
    if(['addition','additionTheme'].includes(field)&&state.browse!=='recent')continue;
    const value=state[field];if(value!=null&&value!==''&&value!==DEFAULTS170[field])params.set(key,String(value));
  }
  if(Number.isSafeInteger(state.page)&&state.page>1)params.set('page',String(state.page));
  return url;
}

// Restores a validated subset; unknown or oversized values are ignored.
export function readCatalogParams170(params){
  const state={};if(!params||typeof params.getAll!=='function')return state;
  for(const [field,key] of Object.entries(MULTI170)){
    const values=params.getAll(key).map(value=>cleanText(value,80)).filter(Boolean).slice(0,64);
    if(!values.length)continue;state[field]=field==='flags170'?[...new Set(values.filter(value=>FLAG_KEYS170.has(value)))]:field==='tags'?canonicalPositionCategories212(values):[...new Set(values)];
  }
  const query=params.get('q');if(query!=null&&cleanText(query,200)!=null)state.query=query;
  if(['all','any'].includes(params.get('match')))state.categoryMatch=params.get('match');
  if(['all','recent'].includes(params.get('view')))state.browse=params.get('view');
  for(const [field,key] of [['addition','add'],['additionTheme','theme'],['sort','sort']]){const value=params.get(key);if(value!=null&&cleanText(value,80))state[field]=value;}
  const commit=params.get('rc');if(commit&&/^[0-9a-f]{7,40}$/.test(commit))state.recent170=commit;
  const page=pageNumber170(params.get('page'),1e6);if(page)state.page=page;
  return state;
}
export function hasCatalogParams170(params){return CATALOG_PARAMS170.some(key=>params?.has?.(key));}

// Original card art stays the detail image. Thumbnails are generated by
// scripts/make-card-thumbs.ps1 next to each native pack's cards folder.
export function thumbnailUrl170(path){
  const match=/^(assets\/native\d{3}\/)cards\/(\d{1,6}\.jpg)$/.exec(String(path??''));
  return match?`${match[1]}thumbs/${match[2]}`:null;
}

// Problems the studio already reports elsewhere: DB issues/needs-review state,
// a rejected or locally invalid card write, and related-card links whose target
// no longer exists (the card dialog shows those as unusable connections).
export function createCardProblems170({cards=[],entities=[],writeState=null,localIssue=null}={}){
  const byId=new Map(),targets=new Set(cards.map(card=>`${card.slot}:${card.identity_key}`));
  const add=(id,code,message)=>{const key=String(id);if(!byId.has(key))byId.set(key,[]);const rows=byId.get(key);if(!rows.some(row=>row.code===code))rows.push({code,message});};
  for(const row of entities){
    if(!row||typeof row.entity_type!=='string'||!row.entity_type.startsWith('card_')||row.deleted)continue;
    if(Array.isArray(row.issues)&&row.issues.length)add(row.entity_id,'db_issue','DB에서 확인이 필요한 항목이 있습니다.');
    if(row.state==='saved_needs_review')add(row.entity_id,'needs_review','DB 저장됨 · 구성 확인 필요');
  }
  for(const issue of [writeState?.rejected?writeState:null,localIssue]){
    if(issue&&String(issue.entityType??'').startsWith('card_'))add(issue.entityId,'rejected','저장 전에 확인할 입력이 있습니다.');
  }
  return {get(card){
    const rows=[...(byId.get(String(card.source_id))??[])];
    if((card.links??[]).some(link=>!targets.has(`${link.slot}:${link.identity_key}`)))rows.push({code:'missing_link',message:'사용할 수 없는 관련 카드 연결이 있습니다.'});
    return rows;
  }};
}

export function cardFlagsMatch170(card,flags,{problems=null,missingImages=null,recent=null}={}){
  for(const flag of list(flags)){
    if(flag==='uncategorized'&&(card.tags??[]).some(tag=>typeof tag==='string'&&tag.trim()))return false;
    if(flag==='noImage'&&card.image&&!missingImages?.has(card.source_id))return false;
    if(flag==='problem'&&!(problems?.get(card).length))return false;
    if(flag==='recent'&&recent&&!recent.has(Number(card.source_id)))return false;
  }
  return true;
}

// Mirrors the single card editor: rarity L only on original base cards and it
// disables shop/reward; category lists keep their order and the field maximum.
export function bulkCardPatches170(cards,{rarity=null,addTags=[],removeTags=[],allowedRarities=['N','R','SR','UR'],maxTags=12}={}){
  const patches=[],skipped=[],add=list(addTags),remove=new Set(list(removeTags));
  for(const card of cards){
    const id=String(card.source_id),name=card.name_ko??id;
    if(rarity){
      const allowed=new Set([...allowedRarities.filter(value=>value!=='L'||card.source_id<2390),...(card.source_id<2390?['L']:[])]);
      if(!allowed.has(rarity))skipped.push({card,reason:`${name}: ${rarity} 등급을 쓸 수 없는 카드입니다.`});
      else if(card.rarity!==rarity)patches.push({type:'card_setting',id,card,fields:rarity==='L'?{rarity,stock:false,draw_enabled:false}:{rarity}});
    }
    if(add.length||remove.size){
      const before=list(card.tags),next=[...new Set([...before.filter(tag=>!remove.has(tag)),...add])];
      if(next.length>maxTags)skipped.push({card,reason:`${name}: 카테고리는 ${maxTags}개까지 넣을 수 있습니다.`});
      else if(next.length!==before.length||next.some((tag,index)=>tag!==before[index]))patches.push({type:'card_annotation',id,card,fields:{tags:next}});
    }
  }
  return {patches,skipped};
}

// Shift-click selects the visible range between the last clicked card and this one.
export function selectRange170(selected,orderedIds,anchor,target,on){
  const next=new Set(selected),from=orderedIds.indexOf(anchor),to=orderedIds.indexOf(target);
  const ids=from<0||to<0?[target]:orderedIds.slice(Math.min(from,to),Math.max(from,to)+1);
  for(const id of ids){if(on)next.add(id);else next.delete(id);}
  return next;
}
